export function parseLangs(s: string | undefined): Lang[] {
  const out = (s ?? 'fr').split(',').map((x) => x.trim()).filter((x): x is Lang => (LANGS as string[]).includes(x));
  return out.length ? [...new Set(out)] : ['fr'];
}
/** Libellé dans une ou plusieurs langues (rapport bilingue : « عربي / Français »). */
export function label(key: string, langs: Lang[]): string {
  const e = LABELS[key];
  return e ? langs.map((l) => e[l]).join(' / ') : key;
}
/** Nom multilingue (jsonb {fr,ar,en}) : première langue disponible parmi celles demandées, puis repli. */
export function pick(name: Record<string, string> | null | undefined, langs: Lang[]): string {
  if (!name) return '';
  const got = langs.map((l) => name[l]).filter(Boolean);
  return got.length ? [...new Set(got)].join(' / ') : (name.fr ?? name.en ?? name.ar ?? '');
}
